using UnityEngine;
using UnityEngine.Rendering;

/// <summary>
/// The "physical object" look of a draggable piece (ruler, set square, eraser).
/// - Resting on the desk: tight, sharp shadow.
/// - Lifted (grabbed): the piece grows a little, the shadow moves away and becomes soft,
///   and the piece is drawn above everything (SortingGroup order).
/// - Dropped: a small squash, as if it landed on the desk.
/// The hover outline sprite (a ring around the silhouette) is also referenced here so
/// DraggableObject can use it instead of building one.
/// </summary>
[DisallowMultipleComponent]
[RequireComponent(typeof(SortingGroup))]
public class PieceLook : MonoBehaviour
{
    [Header("Parts")]
    [SerializeField] private Transform visual;               // what grows when lifted
    [SerializeField] private SpriteRenderer shadowSharp;     // shadow while resting
    [SerializeField] private SpriteRenderer shadowSoft;      // blurred shadow while lifted
    [SerializeField] private GameObject outlineRoot;         // hover ring (inactive by default)
    [SerializeField] private SpriteRenderer[] outlineRenderers;

    [Header("Lift")]
    [SerializeField] private float liftTime = 0.12f;
    [SerializeField] private float liftScale = 1.07f;
    [SerializeField] private Vector2 restShadowOffset = new Vector2(0.12f, -0.16f);   // world units (light from top-left)
    [SerializeField] private Vector2 liftShadowOffset = new Vector2(0.45f, -0.6f);
    [SerializeField, Range(0f, 1f)] private float restShadowAlpha = 0.55f;
    [SerializeField, Range(0f, 1f)] private float liftShadowAlpha = 0.3f;

    [Header("Landing")]
    [SerializeField] private float landTime = 0.2f;
    [SerializeField] private float landSquash = 0.05f;

    [Header("Sorting (SortingGroup order)")]
    [SerializeField] private int restOrder = 5;     // above the comic panels (0), below the character
    [SerializeField] private int liftOrder = 40;    // above everything while held

    public GameObject OutlineRoot => outlineRoot;
    public SpriteRenderer[] OutlineRenderers => outlineRenderers;

    private SortingGroup group;
    private DraggableObject drag;
    private Vector3 visualBase = Vector3.one;
    private float h;               // 0 resting .. 1 lifted
    private bool lifted;
    private float landT = -1f;

    /// <summary>For pieces whose parts are generated by code (the ruler).</summary>
    public void Bind(Transform visual, SpriteRenderer shadowSharp, SpriteRenderer shadowSoft, GameObject outlineRoot, SpriteRenderer[] outlineRenderers)
    {
        this.visual = visual;
        this.shadowSharp = shadowSharp;
        this.shadowSoft = shadowSoft;
        this.outlineRoot = outlineRoot;
        this.outlineRenderers = outlineRenderers;
        visualBase = visual != null ? visual.localScale : Vector3.one;
        Apply();
    }

    private void Awake()
    {
        group = GetComponent<SortingGroup>();
        drag = GetComponent<DraggableObject>();
        if (visual != null) visualBase = visual.localScale;
        group.sortingOrder = restOrder;
    }

    private void OnEnable() { Apply(); }

    private void OnValidate()
    {
        // so the order is right in the editor too, not only while playing
        var g = GetComponent<SortingGroup>();
        if (g != null && !lifted) g.sortingOrder = restOrder;
    }

    public void SetLifted(bool on)
    {
        if (lifted == on) return;
        lifted = on;
        if (!on) landT = 0f;
        if (group != null) group.sortingOrder = on ? liftOrder : restOrder;
    }

    private void LateUpdate()
    {
        h = Mathf.MoveTowards(h, lifted ? 1f : 0f, Time.deltaTime / Mathf.Max(0.001f, liftTime));
        if (landT >= 0f)
        {
            landT += Time.deltaTime;
            if (landT >= landTime) landT = -1f;
        }
        Apply();
    }

    private void Apply()
    {
        float e = h * h * (3f - 2f * h);

        float s = 1f + (liftScale - 1f) * e;
        if (landT >= 0f)
        {
            float k = landT / landTime;
            s *= 1f - landSquash * Mathf.Sin(k * Mathf.PI) * (1f - k);
        }
        if (visual != null) visual.localScale = visualBase * s;

        // The shadow offset is in world space (the light does not rotate with the piece),
        // smaller while the piece is shrunk inside the pencil case.
        float caseScale = drag != null ? drag.ScaleFactor : 1f;
        Vector3 off = (Vector3)(Vector2.Lerp(restShadowOffset, liftShadowOffset, e) * caseScale);
        Vector3 basePos = visual != null ? visual.position : transform.position;
        float shadowGrow = 1f + (liftScale - 1f) * 0.6f * e;

        if (shadowSharp != null)
        {
            shadowSharp.transform.position = basePos + off;
            shadowSharp.transform.localScale = Vector3.one * shadowGrow;
            SetAlpha(shadowSharp, restShadowAlpha * (1f - e));
        }
        if (shadowSoft != null)
        {
            shadowSoft.transform.position = basePos + off;
            shadowSoft.transform.localScale = Vector3.one * shadowGrow;
            SetAlpha(shadowSoft, liftShadowAlpha * e);
        }
    }

    private static void SetAlpha(SpriteRenderer r, float a)
    {
        Color c = r.color;
        if (Mathf.Approximately(c.a, a)) return;
        c.a = a;
        r.color = c;
    }
}
